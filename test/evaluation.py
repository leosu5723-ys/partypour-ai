def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--include-variant-a", action="store_true")
    parser.add_argument("--rerun-b", action="store_true")
    parser.add_argument("--run-e2e", action="store_true",
                        help="preserve saved A and run B/C end to end from raw messages")
    parser.add_argument("--skip-judge", action="store_true",
                        help="skip the independent 1-5 explanation judge")
    parser.add_argument("--judge-model", default=core.JUDGE_MODEL)
    parser.add_argument("--output-dir", default="evaluation_results")
    args = parser.parse_args()

    output_dir = Path(args.output_dir)
    existing_by_id: dict[str, dict] = {}
    existing_path = output_dir / "evaluation_results.json"
    existing_payload: dict[str, Any] = {}
    if existing_path.exists():
        try:
            existing_payload = json.loads(existing_path.read_text(encoding="utf-8"))
            existing_by_id = {row["id"]: row for row in existing_payload.get("cases", [])}
        except (OSError, ValueError, KeyError):
            existing_by_id = {}

    live_requested = args.rerun_b or args.run_e2e or args.include_variant_a
    if not live_requested:
        if not existing_payload:
            parser.error("No saved results exist. Configure the API key and run --run-e2e.")
        print(f"Saved results from {existing_payload.get('generated_at', 'unknown time')}:")
        for variant in ("A", "B", "C"):
            data = existing_payload.get("summary", {}).get(variant, {})
            print(variant, {m: pct_cell(data[m]) for m in METRICS if m in data})
        if not existing_payload.get("execution_scope_by_variant"):
            print("Note: these are legacy saved results from before the final end-to-end protocol; "
                  "run --run-e2e to create the final B/C results.")
        print("No API calls were made and no files were changed.")
        return 0

    pipeline = core.PartyPourPipeline()
    global _PIPELINE_FOR_A
    _PIPELINE_FOR_A = pipeline
    run_a_live = bool(args.include_variant_a and core.API_KEY)
    run_b_live = bool((args.rerun_b or args.run_e2e or args.include_variant_a) and core.API_KEY)
    run_c_live = bool((args.run_e2e or args.include_variant_a) and core.API_KEY)
    run_judge_live = bool(run_c_live and not args.skip_judge and core.API_KEY)
    if (args.rerun_b or args.run_e2e or args.include_variant_a) and not core.API_KEY:
        parser.error("Live evaluation requires PARTYPOUR_API_KEY or OPENAI_API_KEY")

    previous_scopes = existing_payload.get("execution_scope_by_variant", {})
    if (run_a_live or run_b_live or run_c_live) and existing_path.exists():
        history_dir = output_dir / "history"
        history_dir.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        shutil.copy2(existing_path, history_dir / f"evaluation_results_before_{stamp}.json")

    rows = []

    for tc in core.TEST_CASES:
        previous = existing_by_id.get(tc["id"], {})
        previous_outputs = previous.get("outputs", {})
        a_text = core.run_variant_A_minimal_llm(tc) if run_a_live else previous_outputs.get("A")

        if run_b_live:
            try:
                b = core.run_variant_B_simplified(tc, pipeline)
            except Exception as exc:  # preserve the rest of the run for auditability
                b = {"status": "error", "error": f"{type(exc).__name__}: {exc}"}
        else:
            saved_b = previous_outputs.get("B")
            b = saved_b if (
                previous_scopes.get("B") == "end_to_end_live"
                and isinstance(saved_b, dict) and "plan" in saved_b
            ) else {"status": "not_run", "error": "End-to-end Variant B has not been run yet."}

        if run_c_live:
            try:
                c = core.run_variant_C_full_system(tc, pipeline)
            except Exception as exc:  # preserve the rest of the run for auditability
                c = {"status": "error", "error": f"{type(exc).__name__}: {exc}"}
        else:
            saved_c = previous_outputs.get("C")
            c = saved_c if (
                previous_scopes.get("C") == "end_to_end_live"
                and isinstance(saved_c, dict) and "calculation_by_tier" in saved_c
            ) else None

        outputs = {"A": a_text, "B": b, "C": c}
        a_scores = score_a(tc, a_text) if a_text is not None else None
        b_scores = score_b(tc, b, pipeline) if b.get("status") not in ("not_run", "error") else None
        if isinstance(c, dict) and "calculation_by_tier" in c:
            c_scores, diagnostics = score_c(tc, c, pipeline)
        else:
            c_scores, diagnostics = None, ["C_NOT_RUN_OR_ERROR"]

        judge_result = None
        judge_error = None
        if run_judge_live and a_text is not None and b_scores is not None and c_scores is not None:
            try:
                judge_result = judge_explanations(tc, outputs, args.judge_model)
                for variant, scores in (("A", a_scores), ("B", b_scores), ("C", c_scores)):
                    if scores is not None:
                        scores["Explanation Clarity"] = judge_result[variant]["passed"]
            except Exception as exc:
                judge_error = f"{type(exc).__name__}: {exc}"

        row = {
            "id": tc["id"],
            "category": tc["category"],
            "message": tc["message"],
            "outputs": outputs,
            "scores": {"A": a_scores, "B": b_scores, "C": c_scores},
            "explanation_judge": judge_result,
            "explanation_judge_error": judge_error,
            "diagnostics": diagnostics,
        }
        rows.append(row)

    summary = summarize(rows)
    a_ran = all(row["outputs"]["A"] is not None for row in rows)
    b_ran = all(row["outputs"]["B"].get("status") not in ("not_run", "error") for row in rows)
    c_ran = all(isinstance(row["outputs"]["C"], dict)
                and "calculation_by_tier" in row["outputs"]["C"] for row in rows)
    output_dir.mkdir(parents=True, exist_ok=True)
    scope_a = "end_to_end_live" if (run_a_live or a_ran) else "not_run"
    scope_b = "end_to_end_live" if b_ran else "not_run"
    scope_c = "end_to_end_live" if c_ran else "not_run"
    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator_model": core.GEN_MODEL,
        "judge_model": args.judge_model if run_judge_live else None,
        "judge_rubric": "1-5; pass threshold >=4; one call scores A/B/C per case",
        "execution_scope_by_variant": {"A": scope_a, "B": scope_b, "C": scope_c},
        "variant_a_requested": args.include_variant_a,
        "variant_a_ran": a_ran,
        "variant_b_rerun_requested": args.rerun_b or args.run_e2e or args.include_variant_a,
        "variant_b_ran": b_ran,
        "variant_c_rerun_requested": args.run_e2e or args.include_variant_a,
        "variant_c_ran": c_ran,
        "case_count": len(rows),
        "metrics": METRICS,
        "summary": summary,
        "cases": rows,
    }
    (output_dir / "evaluation_results.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    with (output_dir / "evaluation_scores.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "test_id", "category", "variant", *METRICS,
            "explanation_judge_score_1_to_5", "explanation_judge_reason",
        ])
        for row in rows:
            for variant in ("A", "B", "C"):
                scores = row["scores"][variant]
                cells = ["SKIPPED"] * len(METRICS) if scores is None else [
                    "N/A" if scores[m] is None else "PASS" if scores[m] else "FAIL" for m in METRICS
                ]
                judge_item = (row.get("explanation_judge") or {}).get(variant, {})
                writer.writerow([
                    row["id"], row["category"], variant, *cells,
                    judge_item.get("score", ""), judge_item.get("reason", ""),
                ])

    report = build_report(
        rows, summary, a_ran, b_ran, c_ran,
        args.judge_model if run_judge_live else None,
    )
    (output_dir / "EVALUATION_AND_FAILURE_ANALYSIS.md").write_text(report, encoding="utf-8")

    print(f"Evaluated {len(rows)} cases.")
    for variant in ("A", "B", "C"):
        print(variant, {m: pct_cell(summary[variant][m]) for m in METRICS})
    print("Variant A source:", "live rerun" if run_a_live else "saved results" if a_ran else "not run")
    print("Variant B source:", "live rerun" if run_b_live else "saved results" if b_ran else "not run")
    print("Variant C source:", "live end-to-end rerun" if run_c_live else "saved results" if c_ran else "not run")
    print("Explanation judge:", args.judge_model if run_judge_live else "not run")
    print(f"Results written to {output_dir.resolve()}")
    return 0


